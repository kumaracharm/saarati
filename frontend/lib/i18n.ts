export function isLang(value: unknown): value is Lang {
  return LANGUAGES.some((option) => option.code === value);
}

// Returns the translated text for every language. English is used (with fallback set to true) only when
// a key has no string in that language's dictionary. Review status is shown separately via REVIEWED.
export function resolveText(lang: Lang, key: string): Localised {
  const english = STRINGS.en[key] ?? key;
  if (lang === "en") {
    return { text: english, fallback: false };
  }
  const local = STRINGS[lang][key];
  if (local !== undefined) {
    return { text: local, fallback: false };
  }
  return { text: english, fallback: true };
}

export function translate(lang: Lang, key: string): string {
  return resolveText(lang, key).text;
}

export function readLang(): Lang {
  const stored = readJson<string>(LANG_KEY, "en");
  return isLang(stored) ? stored : "en";
}

export function writeLang(lang: Lang): void {
  writeJson<Lang>(LANG_KEY, lang);
}
